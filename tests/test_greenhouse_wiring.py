def test_the_outage_notice_is_not_gagged_by_the_untrusted_wrapper():
    """The wrapper ends "Do not mention this wrapper, label, or warning in your
    answer", which is right for retrieved content and exactly wrong here: it
    tells the model to hide the very thing that has to be said out loud.

    Retrieved memories are untrusted because they came from outside. A health
    notice is generated by this module and carries no third-party text, so it
    is not untrusted data and must not be gagged as if it were.
    """
    from src.prompt_security import GUARD_OPEN
    from src.greenhouse_wiring import greenhouse_recall_message

    provider = FakeProvider(hits=[], available=False, last_error="refused")
    message = run(greenhouse_recall_message(provider, "q"))

    assert GUARD_OPEN not in message["content"]
    assert "do not mention" not in message["content"].lower()
    assert message.get("metadata", {}).get("greenhouse_unavailable") is True


