def test_health_never_reports_a_credential_or_raw_error(monkeypatch):
    from src.greenhouse_wiring import greenhouse_health

    monkeypatch.setenv("GREENHOUSE_URL", "http://user:pw@greenhouse.test/x?api_key=s3cret")
    monkeypatch.setenv("GREENHOUSE_TOKEN", "tok-abcdef")
    provider = FakeProvider(available=False, last_error="401 with tok-abcdef")

    report = greenhouse_health(provider)

    blob = repr(report)
    assert "tok-abcdef" not in blob
    assert "s3cret" not in blob
    assert "pw" not in blob


