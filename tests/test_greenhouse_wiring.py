def test_health_is_down_after_an_outage(monkeypatch):
    """Invariant 13: the failure has to reach Daniel without him going looking.

    The model is told to say so, but that depends on it complying. The status
    panel does not.
    """
    from src.greenhouse_wiring import greenhouse_health

    monkeypatch.setenv("GREENHOUSE_URL", "http://greenhouse.test")
    monkeypatch.setenv("GREENHOUSE_TOKEN", "tok")
    provider = FakeProvider(available=False, last_error="ConnectError: refused")

    report = greenhouse_health(provider)

    assert report["status"] == "down"
    assert report["name"] == "greenhouse"
    assert "model" in report["detail"].lower() or "greenhouse" in report["detail"].lower()


